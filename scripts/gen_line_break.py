#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""UAX #14 の Line_Break から禁則処理の文字表を作る。外部ライブラリ不要。

**約物の表を手で列挙するのをやめるための道具。**
`gen_vertical_orientation.py` と同じ理由で作った ── 規格に書いてあるものを
手で写すと必ず抜ける。JLReq (https://www.w3.org/TR/jlreq/) の Appendix A は
HTML の表で、拾うと取りこぼす。Line_Break は機械可読な一次資料である。

抜き出す類 (UAX #14 の値):

  行頭禁則 (この字で行を始めない)
    CL  Close_Punctuation      終わり括弧類     ）〕］｝〉》」』】
    CP  Close_Parenthesis      終わり丸括弧     ) ]
    EX  Exclamation            区切り約物       ！？
    IS  Infix_Numeric          中点類の一部     ：；，．
    NS  Nonstarter             行頭禁則和字     々ゝヽ ー 小書き仮名 ・
    CJ  Conditional_JP_Starter ★ 下記参照

  行末禁則 (この字で行を終えない)
    OP  Open_Punctuation       始め括弧類       （〔［｛〈《「『【

  分離禁止 (前の字と離さない)
    IN  Inseparable            三点リーダ類     ‥…

★ CJ (Conditional Japanese Starter) は**小書きの仮名・長音記号・繰返し記号**で、
  「厳格なら行頭禁則、緩めるなら許す」の区別のために別の類になっている。
  JLReq §3.1.7 の「々・長音記号・小書きの仮名を緩める本がある」と同じ区別なので、
  **別の表として持つ** ── 今は厳格側 (行頭禁則) で使うが、設定で緩められる形に
  してある。CJ を NS に混ぜてしまうとその区別が復元できない。

★ 2 倍ダーシは類だけでは決まらない:
    U+2014 EM DASH        = B2
    U+2015 HORIZONTAL BAR = AI (曖昧)
  青空文庫のダッシュは U+2015 (Shift-JIS 0x815C) のほうで、AI は
  「文脈で東アジア幅が決まる」という意味しか持たない。**2 倍ダーシの分離禁止は
  この表では決まらないので、CjkBreaks.h 側に明示的な規則として書く。**
  三点リーダ (U+2024..U+2026) は IN なので類で足りる。

データの取得 (リポジトリには含めない):
  curl -o LineBreak.txt https://www.unicode.org/Public/UCD/latest/ucd/LineBreak.txt

使い方:
  python scripts/gen_line_break.py LineBreak.txt [output_path]

既定の出力: lib/Epub/Epub/LineBreakTables.h
"""

import pathlib
import re
import sys

# The classes we keep, grouped by what the typesetter does with them.
LINE_START_PROHIBITED = ["CL", "CP", "EX", "IS", "NS"]
CONDITIONAL_START = ["CJ"]
LINE_END_PROHIBITED = ["OP"]
INSEPARABLE = ["IN"]

WANTED = LINE_START_PROHIBITED + CONDITIONAL_START + LINE_END_PROHIBITED + INSEPARABLE

LINE_RE = re.compile(r"^([0-9A-Fa-f]{4,6})(?:\.\.([0-9A-Fa-f]{4,6}))?\s*;\s*([A-Z0-9]{2,3})")


def load(path):
    """Returns ({class: [(lo, hi), ...]}, version_line, date_line)."""
    by_class = {}
    version = date = ""
    for raw in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        if raw.startswith("# LineBreak-"):
            version = raw.lstrip("# ").strip()
            continue
        if raw.startswith("# Date:"):
            date = raw.lstrip("# ").strip()
            continue
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = LINE_RE.match(line)
        if not m:
            continue
        lo = int(m.group(1), 16)
        hi = int(m.group(2), 16) if m.group(2) else lo
        cls = m.group(3)
        if cls in WANTED:
            by_class.setdefault(cls, []).append((lo, hi))
    return by_class, version, date


def merge(ranges):
    """Sort and coalesce adjacent/overlapping ranges."""
    out = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def group(by_class, classes):
    acc = []
    for c in classes:
        acc.extend(by_class.get(c, []))
    return merge(acc)


def emit_table(name, ranges, classes, comment):
    lines = []
    lines.append("// %s" % comment)
    lines.append("// Line_Break classes: %s. %d ranges." % (", ".join(classes), len(ranges)))
    lines.append("inline constexpr Range %s[] = {" % name)
    row = []
    for lo, hi in ranges:
        row.append("{0x%04X, 0x%04X}," % (lo, hi))
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return lines


def main(data_path, out_path):
    by_class, version, date = load(data_path)
    missing = [c for c in WANTED if c not in by_class]
    if missing:
        sys.exit("no members found for class(es): %s -- is %s the right file?" % (", ".join(missing), data_path))

    starts = group(by_class, LINE_START_PROHIBITED)
    cond = group(by_class, CONDITIONAL_START)
    ends = group(by_class, LINE_END_PROHIBITED)
    insep = group(by_class, INSEPARABLE)

    out = []
    out.append("// GENERATED by scripts/gen_line_break.py -- do not edit by hand.")
    out.append("//")
    out.append("// Source: https://www.unicode.org/Public/UCD/latest/ucd/LineBreak.txt")
    out.append("//   %s" % version)
    out.append("//   %s" % date)
    out.append("//")
    out.append("// Regenerate:")
    out.append("//   curl -o LineBreak.txt https://www.unicode.org/Public/UCD/latest/ucd/LineBreak.txt")
    out.append("//   python scripts/gen_line_break.py LineBreak.txt")
    out.append("//")
    out.append("// Only the classes kinsoku needs are kept; see the script's docstring for why")
    out.append("// each one is here and why CJ is a table of its own.")
    out.append("#pragma once")
    out.append("")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace line_break {")
    out.append("")
    out.append("struct Range {")
    out.append("  uint32_t lo;")
    out.append("  uint32_t hi;")
    out.append("};")
    out.append("")
    out.extend(emit_table("PROHIBITED_AT_LINE_START", starts, LINE_START_PROHIBITED,
                          "Characters a line must not begin with (JLReq 3.1.7)."))
    out.append("")
    out.extend(emit_table("CONDITIONAL_AT_LINE_START", cond, CONDITIONAL_START,
                          "Small kana, the prolonged sound mark and iteration marks: prohibited at "
                          "a line start under the strict rule, allowed under the loose one."))
    out.append("")
    out.extend(emit_table("PROHIBITED_AT_LINE_END", ends, LINE_END_PROHIBITED,
                          "Characters a line must not end with (JLReq 3.1.8)."))
    out.append("")
    out.extend(emit_table("INSEPARABLE", insep, INSEPARABLE,
                          "Must not be separated from what precedes them (JLReq 3.1.10)."))
    out.append("")
    out.append("[[nodiscard]] inline bool inTable(const Range* table, const size_t count, const uint32_t cp) {")
    out.append("  // Binary search: the tables are sorted and coalesced by the generator.")
    out.append("  size_t lo = 0;")
    out.append("  size_t hi = count;")
    out.append("  while (lo < hi) {")
    out.append("    const size_t mid = lo + (hi - lo) / 2;")
    out.append("    if (cp < table[mid].lo) {")
    out.append("      hi = mid;")
    out.append("    } else if (cp > table[mid].hi) {")
    out.append("      lo = mid + 1;")
    out.append("    } else {")
    out.append("      return true;")
    out.append("    }")
    out.append("  }")
    out.append("  return false;")
    out.append("}")
    out.append("")
    out.append("}  // namespace line_break")

    path = pathlib.Path(out_path)
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote %s" % path)
    print("  %s / %s" % (version, date))
    for name, ranges, classes in [
        ("PROHIBITED_AT_LINE_START", starts, LINE_START_PROHIBITED),
        ("CONDITIONAL_AT_LINE_START", cond, CONDITIONAL_START),
        ("PROHIBITED_AT_LINE_END", ends, LINE_END_PROHIBITED),
        ("INSEPARABLE", insep, INSEPARABLE),
    ]:
        total = sum(hi - lo + 1 for lo, hi in ranges)
        print("  %-26s %3d ranges, %5d codepoints  (%s)" % (name, len(ranges), total, ", ".join(classes)))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "lib/Epub/Epub/LineBreakTables.h")
